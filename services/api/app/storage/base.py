"""FileStorage abstraction (docs/DECISIONS.md D-26).

Business logic depends only on this interface. Implementations are synchronous (callers run them
in a thread pool when needed) and are usable from the API and from future background workers.
Object storage could later implement the same interface.

Keys are always generated by the storage implementation, never by clients.
"""

from abc import ABC, abstractmethod
from collections.abc import Iterator
from contextlib import AbstractContextManager
from dataclasses import dataclass
from typing import BinaryIO
from uuid import UUID


class StorageError(Exception):
    """Base class for storage failures. Messages never contain filesystem paths."""


class FileTooLarge(StorageError):
    """The upload exceeded the maximum size allowed for it."""


class StoredFileMissing(StorageError):
    """The key is well-formed but no stored content exists for it."""


class InvalidStorageKey(StorageError):
    """The key is malformed or would resolve outside the storage root."""


@dataclass(frozen=True)
class StoredFile:
    key: str
    size: int
    sha256: str


class PendingUpload(ABC):
    """An upload being received. Nothing is visible at a permanent key until `commit()`."""

    @property
    @abstractmethod
    def size(self) -> int: ...

    @abstractmethod
    def write(self, chunk: bytes) -> None:
        """Append bytes; raises FileTooLarge once the size limit is exceeded."""

    @abstractmethod
    def reader(self) -> AbstractContextManager[BinaryIO]:
        """Finish writing and open the received bytes for validation (seekable, read-only)."""

    @abstractmethod
    def commit(self) -> StoredFile:
        """Atomically move the validated upload to its permanent, server-generated key."""

    @abstractmethod
    def abort(self) -> None:
        """Discard the upload. Safe to call at any time, including after commit."""


class FileStorage(ABC):
    @abstractmethod
    def begin(self, user_id: UUID, namespace: str, max_bytes: int) -> PendingUpload:
        """Start a size-limited upload into the user's namespace (e.g. 'resumes')."""

    @abstractmethod
    def open_stream(self, key: str, chunk_size: int = 64 * 1024) -> Iterator[bytes]:
        """Open stored content for streaming.

        Raises StoredFileMissing immediately (before any byte is yielded) if it does not exist.
        """

    @abstractmethod
    def delete(self, key: str) -> bool:
        """Delete stored content. Idempotent; returns False if nothing existed."""

    @abstractmethod
    def exists(self, key: str) -> bool: ...
